def _build_opt_alt_table(
    isa_condition: str,
    cg_position: str,
    raw_data: list[tuple],
) -> OptimumAltitudeTable:
    entries = [
        OptimumAltitudeEntry(
            weight_kg=row[0] * 1000.0,
            optimum_altitude_ft=float(row[1]),
            tat_c=float(row[2]),
            buffet_margins=BuffetMargins(
                margin_1_30g_ft=float(row[3]),
                margin_1_40g_ft=float(row[4]),
                margin_1_50g_ft=float(row[5]),
            ),
        )
        for row in raw_data
    ]
    return OptimumAltitudeTable(
        isa_condition=isa_condition,
        cg_position=cg_position,
        entries=entries,
    )


