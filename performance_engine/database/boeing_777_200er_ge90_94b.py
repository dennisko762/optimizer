def _build_lrc_rows() -> list[CruiseRow]:
    rows: list[CruiseRow] = []
    for weight_kt, points_raw in _B772_LRC_RAW:
        points = [
            CruisePoint(
                altitude_ft=fl * 100.0,
                n1_pct=n1,
                mach=mach,
                kias=kias,
                ff_per_eng_kg_h=ff,
            )
            for fl, n1, mach, kias, ff in points_raw
        ]
        rows.append(CruiseRow(weight_kg=weight_kt * 1000.0, points=points))
    return rows


def _build_optimum_altitude_table(
    *,
    isa_condition: str,
    cg_position: str,
    raw_data: list[tuple[int, int, int, int, int, int]],
) -> OptimumAltitudeTable:
    entries = [
        OptimumAltitudeEntry(
            weight_kg=weight_kt * 1000.0,
            optimum_altitude_ft=float(opt_alt_ft),
            tat_c=float(tat_c),
            buffet_margins=BuffetMargins(
                margin_1_30g_ft=float(margin_1_30g_ft),
                margin_1_40g_ft=float(margin_1_40g_ft),
                margin_1_50g_ft=float(margin_1_50g_ft),
            ),
        )
        for (
            weight_kt,
            opt_alt_ft,
            tat_c,
            margin_1_30g_ft,
            margin_1_40g_ft,
            margin_1_50g_ft,
        ) in raw_data
    ]
    return OptimumAltitudeTable(
        isa_condition=isa_condition,
        cg_position=cg_position,
        entries=entries,
    )


def _build_optimum_altitude_tables() -> list[OptimumAltitudeTable]:
    raw_tables = [
        ("ISA+10_AND_BELOW", _B772_OPT_ALT_ISA10_BELOW),
        ("ISA+15", _B772_OPT_ALT_ISA15),
        ("ISA+20", _B772_OPT_ALT_ISA20),
    ]
    tables: list[OptimumAltitudeTable] = []
    for isa_condition, raw_data in raw_tables:
        for cg_position in ("FORWARD_7.5_MAC", "MID_30_MAC"):
            tables.append(
                _build_optimum_altitude_table(
                    isa_condition=isa_condition,
                    cg_position=cg_position,
                    raw_data=raw_data,
                )
            )
    return tables


def _build_holding_rows(raw_data: list[tuple[int, list[tuple[int, float, int, int]]]]) -> list[HoldingRow]:
    rows: list[HoldingRow] = []
    for weight_kt, points_raw in raw_data:
        points = [
            HoldingPoint(
                altitude_ft=float(altitude_ft),
                n1_pct=n1_pct,
                kias=kias,
                ff_per_eng_kg_h=ff_per_eng_kg_h,
            )
            for altitude_ft, n1_pct, kias, ff_per_eng_kg_h in points_raw
        ]
        rows.append(HoldingRow(weight_kg=weight_kt * 1000.0, points=points))
    return rows


